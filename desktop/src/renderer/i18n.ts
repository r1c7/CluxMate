const messages: Record<Lang, Record<string, string>> = { en, zh }

export type MessageKey = keyof typeof en

export function isLang(v: unknown): v is Lang {
  return v === 'en' || v === 'zh'
}

/** Best-effort OS/browser language detection. */
export function detectLang(): Lang {
  try {
    const nav = navigator.language || ''
    return nav.toLowerCase().startsWith('zh') ? 'zh' : 'en'
  } catch {
    return DEFAULT_LANG
  }
}

/** Active language for `tGlobal` — kept in sync by applyLang/saveLang. */
let currentLang: Lang = detectLang()

/** Persisted selection, falling back to OS detection. */
export function loadLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_STORAGE_KEY)
    if (isLang(v)) return v
  } catch { /* storage unavailable — fall through to detection */ }
  return detectLang()
}

/** Reflect `lang` on <html lang=…>; falls back to the stored/detected lang. */
export function applyLang(lang: Lang | null | undefined): Lang {
  const l = isLang(lang) ? lang : loadLang()
  currentLang = l
  document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en'
  return l
}

/** Persist + apply; returns the effective lang. */
export function saveLang(lang: Lang): Lang {
  const l = applyLang(lang)
  try { localStorage.setItem(LANG_STORAGE_KEY, l) } catch { /* best effort */ }
  return l
}

/** Translate a key for a specific language, substituting `{var}` placeholders. */
export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const table = messages[lang]
  let s: string = (table && table[key]) || messages.en[key] || key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v))
    }
  }
  return s
}

/** Translate using the currently active language (for non-component code). */
export function tGlobal(key: string, vars?: Record<string, string | number>): string {
  return t(currentLang, key, vars)
}
